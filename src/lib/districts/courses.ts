import type { Text } from "../match/match.ts";

/**
 * Day courses researched by the team (2026-11 documents), checked and adjusted on 2026-11-17:
 * every stop sits inside its district, the order follows a walkable line, and anything that
 * changes often (pop-ups, opening hours, prices) is marked as such.
 */

export interface Photo {
  src: string;
  width: number;
  height: number;
  alt: Text;
  // Openly licensed photos (Wikimedia Commons) carry their author, license and source page.
  credit?: Credit;
}

export interface Credit {
  by: string;
  license: string;
  url: string;
}

export type Icon =
  | "park" | "shops" | "shoe" | "cafe" | "food" | "river" | "history"
  | "view" | "hike" | "temple" | "trail" | "tent" | "museum" | "market"
  | "church" | "beer" | "art" | "perfume" | "game" | "music" | "pottery";
export type Mode = "walk" | "metro" | "bus";

export interface Stop {
  time: string; // 24-hour clock, the suggested arrival
  short: Text; // label on the route map
  summary: Text; // one line, shown before the details
  stay: Text;
  cost?: Text; // a rough range, marked as such
  note?: Text; // one short caution
  icon: Icon;
  mode?: Mode; // how you get here from the previous stop
  name: Text;
  kind: Text;
  body: Text;
  tip?: Text;
  photo?: Photo;
  // How to get here from the previous stop.
  way?: Text;
}

export interface Course {
  slug: string;
  area: Text;
  title: Text;
  intro: Text;
  length: Text;
  start: Text;
  stops: Stop[];
  // Places the team found that sit just across the district line.
  nearby?: Text;
  // One more idea for a longer day.
  more?: Text;
}

const photo = (slug: string, file: string, width: number, height: number, en: string, ko: string, credit?: Credit): Photo => ({
  src: `/districts/${slug}/${file}.jpg`,
  width,
  height,
  alt: { en, ko },
  ...(credit ? { credit } : {}),
});

